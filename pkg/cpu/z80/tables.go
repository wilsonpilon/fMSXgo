func init() {
	// Initialize ZSTable and PZSTable exactly as in fMSX
	for i := 0; i < 256; i++ {
		var f uint8
		if i == 0 {
			f |= FlagZ
		}
		if i >= 128 {
			f |= FlagS
		}
		ZSTable[i] = f

		// Calculate parity
		bits := 0
		for b := 0; b < 8; b++ {
			if (i & (1 << b)) != 0 {
				bits++
			}
		}
		if bits%2 == 0 {
			f |= FlagP
		}
		PZSTable[i] = f
	}
}
